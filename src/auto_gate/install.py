import importlib.resources
import json
import os
import shlex
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

import yaml

from . import __version__
from .config import home, write_json

MARKER = "Generated by Auto local — SSHDotCodes/auto"
# Agents that run a command before each tool call; `auto hook AGENT` speaks each one's format (hooks.py).
COMMAND_HOOKS = ["claude-code", "codex", "gemini", "cursor", "copilot"]
AGENTS = [*COMMAND_HOOKS, "pi", "opencode", "hermes"]
# Executables or config folders whose presence means the agent is installed, for `auto install` without a name.
DETECT = {
    "claude-code": ["claude"],
    "codex": ["codex"],
    "gemini": ["gemini"],
    "cursor": ["cursor-agent", "cursor"],
    "copilot": ["copilot"],
    "pi": ["pi"],
    "opencode": ["opencode"],
    "hermes": ["hermes"],
}
HOOK_COMMAND = "-m auto_gate hook "


def agent_root(agent):
    if agent == "claude-code":
        return Path(os.environ.get("CLAUDE_CONFIG_DIR") or Path.home() / ".claude")
    if agent == "codex":
        return Path(os.environ.get("CODEX_HOME") or Path.home() / ".codex")
    if agent == "gemini":
        return Path.home() / ".gemini"
    if agent == "cursor":
        return Path.home() / ".cursor"
    if agent == "copilot":
        return Path(os.environ.get("COPILOT_HOME") or Path.home() / ".copilot")
    if agent == "pi":
        return Path(os.environ.get("PI_CODING_AGENT_DIR", Path.home() / ".pi" / "agent"))
    if agent == "opencode":
        return Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "opencode"
    if agent == "hermes":
        return Path(os.environ.get("HERMES_HOME", Path.home() / ".hermes"))
    raise ValueError("agent must be one of: " + ", ".join(AGENTS))


def detect_agents():
    """Agents installed for this user: an executable on PATH or the agent's config folder."""
    found = []
    for agent in AGENTS:
        if any(shutil.which(name) for name in DETECT[agent]) or agent_root(agent).is_dir():
            found.append(agent)
    return found


def quote(value):
    if os.name == "nt":
        return '"' + str(value).replace('"', '\\"') + '"'
    return shlex.quote(str(value))


def hook_command(agent, event, block_on_failure=False):
    """Absolute interpreter and data folder, so the hook works from any shell, venv, or working directory.

    `block_on_failure` appends `|| exit 2` (POSIX shells): if the interpreter itself is gone, hosts that treat exit 2
    as a block stop the call instead of skipping the hook. Auto's own failures already answer review."""
    command = f"{quote(sys.executable)} {HOOK_COMMAND}{agent} --event {event} --home {quote(home())}"
    return command + (" || exit 2" if block_on_failure and os.name != "nt" else "")


def backup(path):
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%f")
    copy = path.with_name(path.name + ".auto-backup-" + stamp)
    shutil.copy2(path, copy)
    if os.name != "nt":
        os.chmod(copy, 0o600)


def edit_json(path, change):
    """Apply `change` to a JSON settings file, keeping every other setting; refuses files it cannot parse."""
    previous = path.read_text(encoding="utf-8") if path.exists() else ""
    config = json.loads(previous) if previous.strip() else {}
    if not isinstance(config, dict):
        raise ValueError(f"Expected a JSON object in {path}")
    change(config)
    if previous:
        backup(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".auto-tmp")
    temp.write_text(json.dumps(config, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    if path.exists():
        shutil.copymode(path, temp)
    os.replace(temp, path)


def ours(hook):
    return isinstance(hook, dict) and HOOK_COMMAND in str(hook.get("command", ""))


def set_nested_hook(config, event, entry):
    """Claude Code-style `hooks.EVENT = [{matcher, hooks: [{type, command}]}]`: replace only Auto's entries."""
    hooks = config.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise ValueError("`hooks` must be an object")
    groups = []
    for group in hooks.get(event, []):
        if isinstance(group, dict) and isinstance(group.get("hooks"), list):
            kept = [h for h in group["hooks"] if not ours(h)]
            if not kept:
                continue
            group = {**group, "hooks": kept}
        groups.append(group)
    if entry:
        groups.append(entry)
    if groups:
        hooks[event] = groups
    else:
        hooks.pop(event, None)
    if not hooks:
        config.pop("hooks")


def nested(command, timeout, matcher="*", **extra):
    entry = {"hooks": [{"type": "command", "command": command, "timeout": timeout, **extra}]}
    return {"matcher": matcher, **entry} if matcher is not None else entry


def set_flat_hooks(config, events):
    """Cursor-style `hooks.EVENT = [{command, ...}]`: replace only Auto's entries."""
    if any(events.values()):
        config.setdefault("version", 1)
    hooks = config.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise ValueError("`hooks` must be an object")
    for event, entry in events.items():
        kept = [h for h in hooks.get(event, []) if not ours(h)] + ([entry] if entry else [])
        if kept:
            hooks[event] = kept
        else:
            hooks.pop(event, None)


def configure_hooks(agent, root, enable=True):
    """Register (or remove) Auto's hook entries in the agent's own hook configuration."""

    def cmd(event, block=False):
        return hook_command(agent, event, block)

    if agent in {"claude-code", "codex"}:
        # Codex reads the same hooks.json shape as Claude Code's settings. Timeouts are seconds.
        path = root / ("settings.json" if agent == "claude-code" else "hooks.json")
        entry = nested(cmd("PreToolUse", block=True), 180) if enable else None
        edit_json(path, lambda c: set_nested_hook(c, "PreToolUse", entry))
        return [path]
    if agent == "gemini":
        path = root / "settings.json"
        events = {  # milliseconds
            "BeforeAgent": nested(cmd("BeforeAgent"), 30000, matcher=None, name="auto-context"),
            "AfterTool": nested(cmd("AfterTool"), 30000, name="auto-context"),
            "BeforeTool": nested(cmd("BeforeTool", block=True), 180000, name="auto"),
        }

        def change(config):
            for event, entry in events.items():
                set_nested_hook(config, event, entry if enable else None)

        edit_json(path, change)
        return [path]
    if agent == "cursor":
        path = root / "hooks.json"
        events = {
            "beforeSubmitPrompt": {"command": cmd("beforeSubmitPrompt"), "timeout": 30},
            "postToolUse": {"command": cmd("postToolUse"), "timeout": 30},
            "preToolUse": {"command": cmd("preToolUse"), "timeout": 180, "failClosed": True},
        }
        edit_json(path, lambda c: set_flat_hooks(c, {e: (v if enable else None) for e, v in events.items()}))
        return [path]
    if agent == "copilot":
        # Copilot loads every *.json file in its hooks folder, so Auto owns a file of its own.
        path = root / "hooks" / "auto.json"
        if not enable:
            if path.exists() and HOOK_COMMAND in path.read_text(encoding="utf-8"):
                path.unlink()
            return [path]
        if path.exists() and HOOK_COMMAND not in path.read_text(encoding="utf-8"):
            raise ValueError(f"Refusing to overwrite an existing file: {path}")

        def entry(event, timeout):
            command = cmd(event)
            return {"type": "command", "bash": command, "powershell": "& " + command, "timeoutSec": timeout}

        hooks = {
            "userPromptSubmitted": [entry("userPromptSubmitted", 30)],
            "postToolUse": [entry("postToolUse", 30)],
            # A non-zero exit from preToolUse denies in Copilot; timeouts fail open, so allow cold starts.
            "preToolUse": [entry("preToolUse", 180)],
        }
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps({"version": 1, "hooks": hooks}, indent=2) + "\n", encoding="utf-8")
        return [path]
    raise ValueError("agent must be one of: " + ", ".join(COMMAND_HOOKS))


def owned_write(path, text):
    if path.exists() and MARKER not in path.read_text(encoding="utf-8"):
        raise ValueError(f"Refusing to overwrite an existing file: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def enable_hermes(root, enable=True):
    path = root / "config.yaml"
    previous = path.read_text(encoding="utf-8") if path.exists() else ""
    config = yaml.safe_load(previous) or {}
    if not isinstance(config, dict):
        raise ValueError("Hermes config must be a YAML mapping")
    plugins = config.setdefault("plugins", {})
    enabled = plugins.setdefault("enabled", [])
    if not isinstance(enabled, list):
        raise ValueError("Hermes plugins.enabled must be a list")
    if enable and "auto" not in enabled:
        enabled.append("auto")
    if not enable:
        plugins["enabled"] = [x for x in enabled if x != "auto"]
    if previous:
        backup(path)
    root.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(config, sort_keys=False), encoding="utf-8")
    if os.name != "nt":
        os.chmod(path, 0o600)


def install_agent(agent, root=None):
    root = root or agent_root(agent)
    resources = Path(str(importlib.resources.files("auto_gate"))) / "adapters"
    config = {"python": sys.executable, "autoHome": str(home()), "timeoutMs": 145000}
    if agent in COMMAND_HOOKS:
        paths = configure_hooks(agent, root)
    elif agent in {"pi", "opencode"}:
        folder = "extensions" if agent == "pi" else "plugins"
        path = root / folder / "zz-auto.ts"
        factory = "piPlugin" if agent == "pi" else "opencodePlugin"
        source = resources / (agent + ".mjs")
        code = f"// {MARKER}\nimport {{{factory}}} from {json.dumps(source.as_uri())};\nexport default {factory}({json.dumps(config)});\n"
        owned_write(path, code)
        paths = [path]
    else:
        folder = root / "plugins" / "auto"
        path = folder / "__init__.py"
        code = f"""# {MARKER}
import importlib.util
_spec = importlib.util.spec_from_file_location("auto_hermes_adapter", {str(resources / "hermes.py")!r})
_module = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_module)
def register(ctx):
    return _module.register_with(ctx, {sys.executable!r}, {str(home())!r})
"""
        owned_write(path, code)
        manifest = folder / "plugin.yaml"
        owned_write(
            manifest,
            f"# {MARKER}\nname: auto\nversion: '{__version__}'\ndescription: Local Auto tool-call classification\n",
        )
        enable_hermes(root)
        paths = [path, manifest]
    registry_path = home() / "installations.json"
    registry = json.loads(registry_path.read_text()) if registry_path.exists() else {}
    registry[agent] = {"root": str(root), "paths": [str(p) for p in paths]}
    write_json(registry_path, registry)
    return [str(p) for p in paths]


def uninstall_agent(agent):
    registry_path = home() / "installations.json"
    registry = json.loads(registry_path.read_text()) if registry_path.exists() else {}
    entry = registry.get(agent)
    if not entry:
        return []
    removed = []
    if agent in COMMAND_HOOKS:
        configure_hooks(agent, Path(entry["root"]), enable=False)
        removed = list(entry["paths"])
    for name in entry["paths"] if agent not in COMMAND_HOOKS else []:
        path = Path(name)
        if path.exists() and MARKER in path.read_text(encoding="utf-8"):
            path.unlink()
            removed.append(name)
    if agent == "hermes":
        enable_hermes(Path(entry["root"]), enable=False)
    del registry[agent]
    write_json(registry_path, registry)
    return removed
