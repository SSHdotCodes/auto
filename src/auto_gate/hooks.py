"""Command hooks for agents that run a program before each tool call (`auto hook AGENT`).

The host writes one JSON event to stdin. Auto rebuilds the user's request and the completed actions from what the
host exposes (its transcript file, or prompts recorded by an earlier hook in the same session), scores the proposed
call locally, and prints the host's own decision format. Approval prints nothing, so the host's normal permission
rules still apply. Review asks the user where the host can ask, and blocks where it cannot. No failure is ever
turned into an approval.

Only the standard library and Auto's lightweight client are imported here; PyTorch stays in the daemon.
"""

import hashlib
import json
import re
import sys
import time
from pathlib import Path

from .config import home, write_json

# Claude Code transcripts reach hundreds of MB (full tool results and API request copies). Only this recent tail is
# parsed in full; older lines are scanned for the user's own prompts only.
TRANSCRIPT_TAIL = 16 * 1024 * 1024
LEADING_TYPE = re.compile(rb'\{"type":\s*"([^"]+)"')
USER_TYPE = re.compile(rb'"type":\s*"user"')
SESSION_TTL = 7 * 24 * 3600
# Host- or harness-written text inside user turns. It is context, not the user's own words.
SYNTHETIC = re.compile(
    r"<(system-reminder|task-notification|local-command-stdout|local-command-stderr|bash-stdout|bash-stderr)>"
    r".*?</\1>",
    re.S,
)
NOT_USER = (
    "[Request interrupted by user",
    "Caveat: The messages below were generated by the user while running",
)


def review_reason(detail):
    return f"Auto: review required ({detail})"


def blocks_text(content):
    """Text of a string or a list of content blocks; non-text blocks become short placeholders."""
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return "" if content is None else json.dumps(content, ensure_ascii=False)
    parts = []
    for block in content:
        if not isinstance(block, dict):
            parts.append(str(block))
        elif block.get("type") in {"text", "input_text", "output_text"}:
            parts.append(block.get("text") or "")
        elif block.get("type") in {"image", "input_image"}:
            parts.append("[image]")
        elif block.get("type") == "tool_reference":
            parts.append(f"[tool {block.get('tool_name', '')}]")
        elif block.get("type") == "document":
            parts.append("[document]")
    return "\n".join(p for p in parts if p)


def user_text(value):
    text = SYNTHETIC.sub("", blocks_text(value)).strip()
    return "" if not text or text.startswith(NOT_USER) else text


def parse(line):
    try:
        record = json.loads(line)
    except ValueError:
        return None  # e.g. a partially written last line
    return record if isinstance(record, dict) else None


def claude_user_prompt(record):
    """The user's own words in a transcript record, or "" (tool results, meta/skill text, summaries, subagents)."""
    message = record.get("message")
    if (
        record.get("type") != "user"
        or not isinstance(message, dict)
        or record.get("isMeta")
        or record.get("isCompactSummary")
        or record.get("isSidechain")
    ):
        return ""
    content = message.get("content")
    if isinstance(content, list) and any(
        isinstance(b, dict) and b.get("type") == "tool_result" for b in content
    ):
        return ""
    return user_text(content)


def claude_records(path, tail=TRANSCRIPT_TAIL):
    """(user prompts before the tail window in file order, parsed records inside the window)."""
    start = max(0, Path(path).stat().st_size - tail)
    early, records = [], []
    with open(path, "rb") as stream:
        offset = 0
        for line in stream:
            here, offset = offset, offset + len(line)
            # Metadata records (API request copies, titles, queue state) are never part of the conversation.
            kind = LEADING_TYPE.match(line)
            if kind and kind.group(1) not in {b"user", b"assistant", b"system"}:
                continue
            if here >= start:
                record = parse(line)
                if record is not None:
                    records.append(record)
            elif USER_TYPE.search(line) and b'"tool_result"' not in line:
                record = parse(line)
                text = claude_user_prompt(record) if record else ""
                if text:
                    early.append(text)
    return early, records


def claude_transcript(path, current_id=None, tail=TRANSCRIPT_TAIL):
    """Claude Code / Claude Agent SDK transcript: follow the active branch back through compactions.

    User prompts come from the whole logical chain (compaction summaries are model-written and skipped). Completed
    tool calls come only from after the most recent compaction, which is the context the agent is acting on.
    """
    early, records = claude_records(path, tail)
    by_id = {r["uuid"]: r for r in records if r.get("uuid")}
    position = {id(r): i for i, r in enumerate(records)}
    tip = next(
        (r for r in reversed(records) if r.get("type") in {"user", "assistant"} and not r.get("isSidechain")),
        None,
    )
    chain, seen, node, compacted, parent = [], set(), tip, False, None
    while node is not None and node.get("uuid") not in seen:
        seen.add(node.get("uuid"))
        if node.get("type") == "system" and node.get("subtype") == "compact_boundary":
            compacted = True
        chain.append((node, compacted))
        parent = node.get("parentUuid") or node.get("logicalParentUuid")
        node = by_id.get(parent)
    chain.reverse()
    users = []
    if parent or not chain:
        # The chain broke: a compaction boundary points at an unrecorded parent, or the branch starts before the
        # parsed window. Earlier prompts are then taken in file order (including any rewound branches).
        first = min((position[id(record)] for record, _ in chain), default=len(records))
        users = early + [t for r in records[:first] if (t := claude_user_prompt(r))]
    calls, history = {}, []
    for record, before_compaction in chain:
        message = record.get("message")
        if not isinstance(message, dict) or record.get("isSidechain"):
            continue
        content = message.get("content")
        if record.get("type") == "user":
            text = claude_user_prompt(record)
            if text:
                users.append(text)
            if before_compaction or not isinstance(content, list):
                continue
            for block in content:
                if isinstance(block, dict) and block.get("type") == "tool_result":
                    call = calls.pop(block.get("tool_use_id"), None)
                    if call:
                        result = blocks_text(block.get("content"))
                        history.append(
                            {**call, "result": ("[error] " if block.get("is_error") else "") + result}
                        )
        elif record.get("type") == "assistant" and isinstance(content, list) and not before_compaction:
            for block in content:
                if (
                    isinstance(block, dict)
                    and block.get("type") == "tool_use"
                    and block.get("id") != current_id
                ):
                    calls[block.get("id")] = {
                        "tool": block.get("name") or "tool",
                        "args": block.get("input", {}),
                    }
    return users, history


def codex_transcript(path, current_id=None, tail=TRANSCRIPT_TAIL):
    """Codex rollout JSONL: user messages (minus injected AGENTS.md / environment / skill blocks) and the tool calls
    completed since the most recent compaction, paired by call_id."""
    users, calls, history = [], {}, []
    start = max(0, Path(path).stat().st_size - tail)
    with open(path, "rb") as stream:
        offset = 0
        for line in stream:
            here, offset = offset, offset + len(line)
            if here < start and b'"role":"user"' not in line.replace(b" ", b""):
                continue
            record = parse(line)
            payload = (record or {}).get("payload")
            if not isinstance(payload, dict):
                continue
            if record.get("type") == "compacted":
                calls, history = {}, []
                continue
            if record.get("type") != "response_item":
                continue
            kind = payload.get("type")
            if kind == "message" and payload.get("role") == "user":
                parts = [
                    b.get("text") or ""
                    for b in payload.get("content") or []
                    if isinstance(b, dict)
                    and b.get("type") == "input_text"
                    and not (b.get("text") or "").lstrip().startswith(CODEX_INJECTED)
                ]
                text = user_text("\n".join(parts))
                if text:
                    users.append(text)
            elif here < start:
                continue
            elif kind in {"function_call", "custom_tool_call", "local_shell_call"} and payload.get("call_id"):
                args = payload.get("arguments", payload.get("input", payload.get("action", {})))
                if isinstance(args, str) and kind == "function_call":
                    try:
                        args = json.loads(args)
                    except ValueError:
                        pass
                if payload["call_id"] != current_id:
                    calls[payload["call_id"]] = {"tool": payload.get("name") or "shell", "args": args}
            elif kind in {"function_call_output", "custom_tool_call_output"}:
                call = calls.pop(payload.get("call_id"), None)
                if call:
                    output = payload.get("output")
                    if isinstance(output, dict):
                        output = output.get("content", output)
                    history.append({**call, "result": blocks_text(output)})
    return users, history


CODEX_INJECTED = (
    "# AGENTS.md instructions",
    "<environment_context>",
    "<user_instructions>",
    "<permissions instructions>",
    "<skill>",
    "<turn_aborted>",
)


# Prompts and completed actions recorded by earlier hooks, for hosts whose hook input has no transcript.
MAX_RECORDED_ACTIONS = 1000
MAX_RECORDED_RESULT = 200_000


def session_path(agent, session):
    digest = hashlib.sha256(f"{agent}\0{session}".encode()).hexdigest()[:32]
    return home() / "sessions" / f"{agent}-{digest}.json"


def load_session(agent, session):
    try:
        state = json.loads(session_path(agent, session).read_text(encoding="utf-8"))
        if isinstance(state, dict) and isinstance(state.get("users"), list):
            return state
    except (OSError, ValueError):
        pass
    return {"users": [], "history": []}


def record_session(agent, session, user=None, action=None):
    """Append to a session's private state under a lock (parallel tool calls finish concurrently)."""
    from filelock import FileLock

    from .fit import shorten

    folder = home() / "sessions"
    folder.mkdir(parents=True, exist_ok=True, mode=0o700)
    path = session_path(agent, session)
    with FileLock(str(path) + ".lock", timeout=10):
        state = load_session(agent, session)
        if user:
            state["users"].append(user)
        if action:
            result = text_value(action.get("result", ""))
            state["history"].append({**action, "result": shorten(result, MAX_RECORDED_RESULT)})
            del state["history"][:-MAX_RECORDED_ACTIONS]
        write_json(path, state)
    now = time.time()
    for old in folder.glob("*.json"):
        try:
            if now - old.stat().st_mtime > SESSION_TTL:
                old.unlink()
                Path(str(old) + ".lock").unlink(missing_ok=True)
        except OSError:
            pass


def text_value(value):
    if isinstance(value, str):
        return value
    return json.dumps(value, ensure_ascii=False)


def loads_maybe(value):
    if isinstance(value, str):
        try:
            return json.loads(value)
        except ValueError:
            return value
    return value if value is not None else {}


class Host:
    """One agent's hook dialect: how to read the proposed call and its context, and how to answer."""

    name = ""
    decide = ()  # events that score a proposed call; others only record context and never block

    def event_name(self, event, given):
        # Unnamed events are treated as tool decisions: a missing name must not skip the check.
        return given or event.get("hook_event_name") or self.decide[0]

    def foreign(self, event):
        """Another agent running this agent's hook configuration (several read Claude Code's settings)."""
        return False

    def call(self, event):
        return {"tool": event["tool_name"], "args": event.get("tool_input", {})}

    def context(self, event):
        raise NotImplementedError

    def record(self, name, event):
        pass

    def respond(self, decision, reason):
        """(stdout, exit code) for a decision. Approval prints nothing: the host's own rules still apply."""
        raise NotImplementedError

    def recorded(self, name):
        return "", 0


class ClaudeCode(Host):
    """Claude Code (and the Claude Agent SDK) PreToolUse, with context from the session transcript."""

    name = "claude-code"
    decide = ("PreToolUse",)

    def foreign(self, event):
        # Cursor and Copilot CLI also run hooks from Claude Code settings files, with their own payloads.
        return "cursor_version" in event or "toolName" in event

    def context(self, event):
        path = event.get("transcript_path")
        if not path or not Path(path).exists():
            return [], []
        return claude_transcript(path, event.get("tool_use_id"))

    def respond(self, decision, reason):
        if decision == "approve":
            return "", 0
        output = {
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "deny" if decision == "deny" else "ask",
                "permissionDecisionReason": reason,
            }
        }
        return json.dumps(output, ensure_ascii=False), 0


class Codex(ClaudeCode):
    """Codex CLI PreToolUse. Codex hooks cannot ask the user, so review blocks with an explanation."""

    name = "codex"

    def foreign(self, event):
        return False

    def context(self, event):
        path = event.get("transcript_path")
        if not path or not Path(path).exists():
            return [], []
        return codex_transcript(path, event.get("tool_use_id"))

    def respond(self, decision, reason):
        if decision == "approve":
            return "", 0
        if decision == "review":
            reason += ". Ask the user to confirm this exact action; Auto re-checks it with their answer."
        output = {
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "deny",
                "permissionDecisionReason": reason,
            }
        }
        return json.dumps(output, ensure_ascii=False), 0


class Recorded(Host):
    """Hosts whose tool hooks carry no transcript: prompt and post-tool hooks record the session privately."""

    session_field = "session_id"
    prompt_events = ()
    result_events = ()

    def session(self, event):
        value = event.get(self.session_field)
        if not value:
            raise ValueError("hook input has no session id")
        return str(value)

    def context(self, event):
        state = load_session(self.name, self.session(event))
        return state["users"], state["history"]

    def record(self, name, event):
        if name in self.prompt_events:
            record_session(self.name, self.session(event), user=user_text(event.get("prompt") or ""))
        elif name in self.result_events:
            record_session(
                self.name, self.session(event), action={**self.call(event), "result": self.result(event)}
            )

    def result(self, event):
        raise NotImplementedError


class Gemini(Recorded):
    """Gemini CLI: BeforeAgent records the prompt, AfterTool the result, BeforeTool decides."""

    name = "gemini"
    decide = ("BeforeTool",)
    prompt_events = ("BeforeAgent",)
    result_events = ("AfterTool",)

    def result(self, event):
        response = event.get("tool_response") or {}
        if not isinstance(response, dict):
            return text_value(response)
        value = blocks_text(response.get("llmContent", response.get("returnDisplay", "")))
        return ("[error] " + text_value(response["error"]) + "\n" if response.get("error") else "") + value

    def respond(self, decision, reason):
        if decision == "approve":
            return "", 0
        if decision == "review":
            reason += ". Ask the user to confirm this exact action; Auto re-checks it with their answer."
        return json.dumps({"decision": "deny", "reason": reason}, ensure_ascii=False), 0


class Cursor(Recorded):
    """Cursor: beforeSubmitPrompt records the prompt, postToolUse the result, preToolUse decides.

    Cursor treats empty output from a permission hook as invalid, so approval is an explicit allow, and its
    preToolUse does not enforce ask, so review blocks with an explanation."""

    name = "cursor"
    session_field = "conversation_id"
    decide = ("preToolUse",)
    prompt_events = ("beforeSubmitPrompt",)
    result_events = ("postToolUse",)

    def call(self, event):
        return {"tool": event["tool_name"], "args": loads_maybe(event.get("tool_input"))}

    def result(self, event):
        return text_value(event.get("tool_output", ""))

    def respond(self, decision, reason):
        if decision == "approve":
            return json.dumps({"permission": "allow"}), 0
        if decision == "review":
            reason += ". Ask the user to confirm this exact action; Auto re-checks it with their answer."
        output = {"permission": "deny", "user_message": reason, "agent_message": reason}
        return json.dumps(output, ensure_ascii=False), 0

    def recorded(self, name):
        return (json.dumps({"continue": True}) if name == "beforeSubmitPrompt" else "{}"), 0


class Copilot(Recorded):
    """GitHub Copilot CLI: userPromptSubmitted records the prompt, postToolUse the result, preToolUse decides."""

    name = "copilot"
    session_field = "sessionId"
    decide = ("preToolUse",)
    prompt_events = ("userPromptSubmitted",)
    result_events = ("postToolUse",)

    def call(self, event):
        return {"tool": event["toolName"], "args": loads_maybe(event.get("toolArgs"))}

    def result(self, event):
        result = event.get("toolResult") or {}
        if isinstance(result, dict):
            prefix = "" if result.get("resultType") in (None, "success") else f"[{result['resultType']}] "
            return prefix + text_value(result.get("textResultForLlm", ""))
        return text_value(result)

    def respond(self, decision, reason):
        if decision == "approve":
            return "", 0
        output = {
            "permissionDecision": "deny" if decision == "deny" else "ask",
            "permissionDecisionReason": reason,
        }
        return json.dumps(output, ensure_ascii=False), 0


HOSTS = {host.name: host for host in [ClaudeCode(), Codex(), Gemini(), Cursor(), Copilot()]}


def evaluate(host, name, event, judge):
    """Returns (decision, reason); decision "pass" means this event only records context or is not ours."""
    if not isinstance(event, dict):
        raise ValueError("hook input must be a JSON object")
    if host.foreign(event):
        return "pass", ""
    if name not in host.decide:
        host.record(name, event)
        return "pass", ""
    call = host.call(event)
    users, history = host.context(event)
    if not users:
        return "review", review_reason("no user request in this session's context")
    payload = {"user_request": "\n\n".join(users), "history": history, "call": call, "context_complete": True}
    result = judge(payload)
    decision = result.get("decision")
    if decision not in {"approve", "deny", "review"}:
        return "review", review_reason("invalid classifier response")
    return decision, result.get("reason") or f"Auto: {decision}"


def run(agent, raw, judge=None, event_name=None):
    """Handle one hook event. Returns (stdout, exit code) in the host's format."""
    host = HOSTS[agent]
    if judge is None:
        from .client import score as judge
    name = event_name or host.decide[0]
    try:
        event = json.loads(raw)
        name = host.event_name(event if isinstance(event, dict) else {}, event_name)
        decision, reason = evaluate(host, name, event, judge)
    except Exception as exc:  # noqa: BLE001 - any failure is a review, never an approval
        decision, reason = "review", review_reason(f"Auto could not evaluate this call: {type(exc).__name__}")
    if name not in host.decide:
        return host.recorded(name)  # recording never blocks the prompt or the agent
    if decision == "pass":
        return "", 0
    return host.respond(decision, reason)


def main(agent, event_name=None):
    output, code = run(agent, sys.stdin.read(), event_name=event_name)
    if output:
        sys.stdout.write(output + "\n")
    return code
